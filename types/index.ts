export type Color = { name: string; hex: string };
export type ProductImage = { src: string; alt: string };
export type Product = {
  id: string;
  slug: string;
  name: string;
  sku: string;
  category: string;
  subBrand: string;
  collections: string[];
  occasion: string[];
  fabric: string;
  technique: string;
  price: number;
  compareAtPrice: number | null;
  colors: Color[];
  sizes: string[];
  stock: Record<string, number>;
  images: ProductImage[];
  description: string;
  details: string[];
  care: string[];
  tags: string[];
  createdAt: string;
  popularity: number;
};
export type Category = { slug: string; name: string; image: string };
export type Collection = {
  slug: string;
  title: string;
  description?: string;
  banner?: string;
  seoText?: string;
  filter: (p: Product) => boolean;
};
export type SortKey = 'featured' | 'new' | 'price-asc' | 'price-desc' | 'bestselling';
export type Filters = {
  category: string[];
  size: string[];
  color: string[];
  fabric: string[];
  occasion: string[];
  discount: number | null;
  priceMin: number | null;
  priceMax: number | null;
};
export type CartLine = { key: string; productId: string; slug: string; name: string; image: string; size: string; color: string; price: number; compareAtPrice: number | null; qty: number; maxQty: number };
export type Address = { id: string; name: string; phone: string; pincode: string; line1: string; line2: string; landmark: string; city: string; state: string; type: 'Home' | 'Work' };
export type Order = {
  id: string;
  createdAt: string;
  email: string;
  phone: string;
  address: Address;
  delivery: { method: 'standard' | 'express'; fee: number; eta: string };
  payment: { method: string; fee: number };
  lines: CartLine[];
  subtotal: number;
  discount: number;
  coupon: string | null;
  giftWrap: boolean;
  total: number;
  status: 'Placed' | 'Packed' | 'Shipped' | 'Out for delivery' | 'Delivered';
};
